import { rub } from './money';

/**
 * Предварительная оценка ремонта по описанию неисправности.
 * Используется и в приложении (показ клиенту), и на сервере (сохранение в заявке).
 * Точную смету мастер согласует после диагностики.
 */
export function estimateRepair(problem: string | null | undefined): { min: number; max: number } {
  const p = (problem ?? '').toLowerCase();
  const rules: [RegExp, number, number][] = [
    [/накип|декальцин|очист|чист/, 1500, 3000],
    [/теч|протека|лужа|капа/, 2500, 6000],
    [/не греет|холодн|тэн|нагрев|термоблок/, 3500, 9000],
    [/помп|насос|не кач|не подаёт|не подает|давлен/, 3000, 8000],
    [/жернов|кофемолк|не мелет|молка/, 2500, 7000],
    [/капучин|молок|пена|вспен/, 1500, 4000],
    [/ошибк|не включ|плат|электрон|дисплей/, 3000, 12000],
  ];
  const hit = rules.find(([re]) => re.test(p));
  return hit ? { min: rub(hit[1]), max: rub(hit[2]) } : { min: rub(1500), max: rub(8000) };
}

/** Стоимость диагностики, входит в стоимость ремонта. */
export const DIAGNOSTICS_PRICE = rub(800);
